export const bessModels: BessModel[] = rawModels.map(createBessModel);

function reliabilityFor(model: BessModel): SourceReliability {
  if (model.dataConfidence === "confirmed" || model.dataConfidence === "calculated") {
    return "certified_data";
  }
  if (model.dataConfidence === "estimated") return "preliminary_assumption";
  return "pending_validation";
}

