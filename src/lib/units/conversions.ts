export function m2ToHa(valueM2: number): number {
  return valueM2 / 10000;
}

export function kgToTonnes(valueKg: number): number {
  return valueKg / 1000;
}

export function tonnesToKg(valueT: number): number {
  return valueT * 1000;
}

export function mwToKw(valueMw: number): number {
  return valueMw * 1000;
}

export function mwhToKwh(valueMwh: number): number {
  return valueMwh * 1000;
}
